function parseSuites() {
  const src = exists('wdio.conf.js') ? read('wdio.conf.js') : '';
  const i = src.indexOf('suites:');
  if (i < 0) return {};
  const body = block(src, src.indexOf('{', i));
  return Object.fromEntries([...body.matchAll(/(\w+):\s*\[([\s\S]*?)\]/g)]
    .map((m) => [m[1], [...m[2].matchAll(/'\.\/(test\/specs\/[^']+)'/g)].map((x) => x[1])]));
}

// --- helper functions that contain steps (spec-local + session.js) ---
function helperBodies(src) {
  const map = {};
  const params = (p) => p.split(',').map((x) => {
    const [name, def] = x.split('=').map((y) => y.trim());
    return { name: name.replace(/[{}]/g, ''), def: def && /^['"`]/.test(def) ? def.slice(1, -1) : undefined };
  }).filter((x) => x.name);
  for (const m of src.matchAll(/(?:export )?(?:async )?function (\w+)\s*\(([^)]*)\)\s*\{/g)) {
    map[m[1]] = { body: block(src, m.index + m[0].length - 1), params: params(m[2]) };
  }
  for (const m of src.matchAll(/const (\w+) = (?:async )?\(([^)]*)\) =>([\s\S]*?\n)(?=\S|\s*\n)/g)) {
    map[m[1]] = { body: m[3], params: params(m[2]) };
  }
  return map;
}
const SESSION_HELPERS = exists('test/helpers/session.js') ? helperBodies(read('test/helpers/session.js')) : {};

function splitArgs(argStr) {                   // top-level commas only
  const out = []; let depth = 0, q = null, cur = '';
  for (let i = 0; i < argStr.length; i++) {
    const c = argStr[i];
    if (q) { cur += c; if (c === '\\') { cur += argStr[++i]; continue; } if (c === q) q = null; continue; }
    if (c === '"' || c === "'" || c === '`') { q = c; cur += c; continue; }
    if ('([{'.includes(c)) depth++;
    if (')]}'.includes(c)) depth--;
    if (c === ',' && depth === 0) { out.push(cur.trim()); cur = ''; continue; }
    cur += c;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}

function stepsIn(body, helpers, depth = 0, vars = {}) {
  const out = [];
  const loop = body.match(/for \(const (\w+) of \[([^\]]+)\]\)/);
  const loopVals = loop ? loop[2].split(',').map((x) => x.trim()).map((x) => {
    const k = x.match(/^MENU\.(\w+)$/)?.[1]; return k ? MENU[k] || k : x.replace(/['"`]/g, '');
  }) : null;
  const re = /\b(step|checkpoint)\(\s*(['"`])((?:\\.|(?!\2)[^\\])*)\2|\b(\w+)\s*\(/g;
  for (const m of body.matchAll(re)) {
    if (m[1]) {
      let name = m[3].replace(/\\(["'`])/g, '$1');
      const usesLoop = loop && name.includes('${' + loop[1] + '}');
      name = name.replace(/\$\{(\w+)\}/g, (_, v) => (v in vars ? vars[v] : `<${v}>`)).replace(/\s{2,}/g, ' ').trim();
      const ctx = body.slice(Math.max(0, m.index - 200), m.index);
      const conditional = /(?:\bif \([^\n]*\)|\belse)\s*\{\s*(?:\/\/[^\n]*\n\s*)*(?:await\s+)?$/.test(ctx);
      out.push(name + (conditional ? ' _(only if applicable)_' : '') + (usesLoop ? ` – for each: ${loopVals.join(', ')}` : ''));
    } else if (m[4] && depth < 3 && helpers[m[4]] && !['step', 'checkpoint'].includes(m[4])) {
      const h = helpers[m[4]];
      const open = m.index + m[0].length - 1;
      let d = 0, end = open;
      for (; end < body.length; end++) { if (body[end] === '(') d++; if (body[end] === ')' && --d === 0) break; }
      const args = splitArgs(body.slice(open + 1, end));
      const v = {};
      h.params.forEach((p, i) => {
        const a = args[i];
        v[p.name] = a && /^['"`]/.test(a) ? a.slice(1, -1) : (a === undefined ? (p.def ?? `<${p.name}>`) : `<${p.name}>`);
      });
      out.push(...stepsIn(h.body, helpers, depth + 1, v));
    }
  }
  return out.filter((s, i) => s !== out[i - 1]);
}

function parseSpecs() {
  const dir = path.join(ROOT, 'test/specs');
  if (!fs.existsSync(dir)) return [];
  const tests = [];
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.e2e.js')).sort()) {
    const rel = `test/specs/${f}`;
    const src = read(rel);
    const suite = src.match(/describe\(\s*(['"`])(.+?)\1/)?.[2] || f;
    const helpers = { ...SESSION_HELPERS, ...helperBodies(src) };
    for (const m of src.matchAll(/\bit\(\s*(['"`])(.+?)\1\s*,[^{]*\{/g)) {
      const body = block(src, m.index + m[0].length - 1);
      tests.push({
        suite, title: m[2], spec: rel,
        data: [...new Set([...body.matchAll(/users\.(\w+)\b(?!['"])/g)].map((x) => x[1]).filter((x) => x !== 'js'))].map((x) => `users.${x}`).join(', ')
          || ((x) => (x ? `users.${x[2]}` : ''))(/(ensureLoggedIn|loginAs)\(users\.(\w+)/.exec(src)),
        steps: stepsIn(body, helpers),
      });
    }
  }
  return tests;
}

// --- methods / exported functions with their doc comment ---
function parseMethods(rel) {
  const src = read(rel);
  const lines = src.split('\n');
  const out = [];
  lines.forEach((line, i) => {
    let m = line.match(/^\s{2}(?:async\s+)?(\w+)\s*\(([^)]*)\)\s*\{/) || line.match(/^export (?:async )?function (\w+)\s*\(([^)]*)\)/);
    if (!m || ['if', 'for', 'while', 'switch', 'catch', 'constructor'].includes(m[1])) return;
    if (/^\s*get\s/.test(line)) return;
    let doc = line.match(/\}\s*\/\/\s*(.+)$/)?.[1] || '';
    if (!doc) {                             // look upwards for /** … */ or // comment
      let j = i - 1;
      if (/^\s*\*\/\s*$/.test(lines[j]) || /\*\/\s*$/.test(lines[j])) {
        const parts = [];
        while (j >= 0 && !/\/\*\*/.test(lines[j])) { parts.unshift(lines[j]); j--; }
        if (j >= 0) parts.unshift(lines[j]);
        doc = parts.join(' ').replace(/\/\*\*|\*\/|^\s*\*|\s\*\s/g, ' ').replace(/@\w+[^.]*$/, '').replace(/\s+/g, ' ').trim();
      } else if (/^\s*\/\/\s*(.+)/.test(lines[j]) && !/^\s*\/\/\s*[-=]{3,}/.test(lines[j])) {
        doc = lines[j].replace(/^\s*\/\/\s*/, '');
      }
    }
    doc = doc.split(/(?<!\be\.g|\bi\.e|\betc)\.\s+(?=[A-Z«`])/)[0].replace(/\.$/, '');
    if (doc.length > 200) doc = doc.slice(0, 197).replace(/\s\S*$/, '') + '…';
    if (!doc) doc = m[1].replace(/([A-Z])/g, ' $1').toLowerCase().replace(/^./, (c) => c.toUpperCase());
    const params = m[2].replace(/\s+/g, ' ').replace(/\{[^}]*\}\s*=\s*\{\}/g, '{…opts}').trim();
    out.push({ name: m[1], params, doc });
  });
  return out.filter((x, i, a) => a.findIndex((y) => y.name === x.name) === i);
}

